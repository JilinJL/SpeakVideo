import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const nodes = new Map();
const node = id => { if (!nodes.has(id)) nodes.set(id, {style:{},classList:{toggle(){}},setAttribute(){},hidden:false,open:true,textContent:'',value:'',getBoundingClientRect:()=>({left:0,width:100})}); return nodes.get(id); };
let animation;
const scope = {document:{getElementById:node}, window:{}, ResizeObserver:class{observe(){}}, fetch:async()=>({ok:true,arrayBuffer:async()=>new ArrayBuffer(0)}), requestAnimationFrame:fn=>(animation=fn,1), cancelAnimationFrame:()=>{animation=null;}};
vm.createContext(scope);
vm.runInContext(fs.readFileSync('speakvideo/static/reference-editor.js','utf8')+'\nthis.Editor=ReferenceEditor;',scope);
let calls=[], changes=[],fail=false;
const editor = new scope.Editor({request:async(path,method,body)=>{calls.push(body);if(fail)throw Error('crop failed');return {reference_id:'crop',duration:body.end-body.start};},onChange:r=>changes.push(r),onError:e=>{throw e;}});
editor.draw=()=>{};
editor.ctx={currentTime:0,decodeAudioData:async()=>({duration:10}),resume:async()=>{},destination:{},createBufferSource:()=>({connect(){},disconnect(){},start(){},stop(){}})};
await editor.load({reference_id:'original',preview_url:'/reference.wav',duration:10},'test');
assert.equal(changes.at(-1).reference_id,'original');
assert.equal((await editor.prepare()).reference_id,'original');
assert.equal(calls.length,0,'full audio needs no crop request');
editor.setSelection(2,5);
assert.equal(changes.at(-1).duration,3);
assert.equal(calls.length,0,'dragging is local');
assert.equal((await editor.prepare()).reference_id,'crop');
assert.equal(calls[0].start,2);assert.equal(calls[0].end,5);
await editor.prepare();assert.equal(calls.length,1,'unchanged selection reuses exact PCM');
editor.locked=true;editor.setSelection(0,10);assert.equal(editor.start,2);editor.locked=false;
await editor.play();editor.ctx.currentTime=1;animation();
assert.equal(node('referencePosition').textContent,'3.00 / 10.00 秒');
assert.equal(node('referencePlayhead').style.left,'30%');
editor.source.onended();assert.equal(node('referencePosition').textContent,'5.00 / 10.00 秒');
node('referenceWaveArea').setPointerCapture=()=>{};
const click = {clientX:70,pointerId:1,target:{id:'referenceWave'},preventDefault(){}};
editor.beginDrag(click);await editor.finishDrag();
assert.equal(editor.start,2);assert.equal(editor.end,5,'clicking must not alter the crop');
assert.equal(node('referencePosition').textContent,'7.00 / 10.00 秒');
editor.ctx.currentTime+=.3;animation();assert.equal(node('referencePosition').textContent,'7.30 / 10.00 秒');
editor.stop();
editor.beginDrag({...click,clientX:20,target:{id:'trimStartHandle'}});
editor.drag({...click,clientX:30});await editor.finishDrag();
assert.equal(editor.start,3,'dragging still edits the crop');
editor.setSelection(3,6);fail=true;
await assert.rejects(editor.prepare(),/crop failed/);assert.equal(editor.pending,false);
fail=false;await editor.prepare();assert.equal(calls.at(-1).start,3);
editor.setSelection(4,7);
let release;editor.request=()=>new Promise(resolve=>release=resolve);
const stale=editor.prepare();editor.close();release({reference_id:'stale',duration:3});
await assert.rejects(stale,/角色原声已切换/);
assert.notEqual(changes.at(-1)?.reference_id,'stale');
console.log('reference editor: full source, lazy exact crop, retry, freeze, progress and stale response passed');
